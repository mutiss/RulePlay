// Upload-key credentials live outside the project, in ../RulePlay-keys. Without them, release builds fall back
// to the local debug key so the optimised build can still be run from Android Studio.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("../RulePlay-keys/keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.mutissx.ruleplay"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.mutissx.ruleplay"
        minSdk = 30
        targetSdk = 36
        versionCode = 2
        versionName = "1.1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProperties.isNotEmpty()) {
            create("upload") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // R8: shrinks, optimises and obfuscates. The mapping file is embedded in the AAB, so Play Console
            // de-obfuscates crash and ANR reports.
            optimization {
                enable = true
            }
            signingConfig = signingConfigs.findByName("upload") ?: signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    androidResources {
        generateLocaleConfig = true
    }
    sourceSets {
        // Unit tests parse the real bundled content to guarantee its integrity.
        getByName("test").resources.directories.add("src/main/assets")
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

